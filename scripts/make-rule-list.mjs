const cell = (text) => text.replace(/\|/g, '\\|');

function build(lang) {
  setLangSource(() => lang);
  const t = TEXT[lang];
  /** Internal document names do not exist in the public repository — replace them with a meaningful phrase */
  const publicSource = (source) =>
    source
      .replace(/0[1-5]_[^\s]+\.md/g, t.internal)
      .split('AAS 참조모델 제약조건 spec_260812.pdf') // i18n-ignore — file name of the source document
      .join(tr('AAS 참조모델 제약조건 spec_260812.pdf')) // i18n-ignore — file name of the source document
      .replace(/\s+/g, ' ')
      .trim();
  const lines = [
    t.switcher,
    '',
    ...t.head(ALL_RULES.length),
    ...Object.values(t.layers).map((layer) => `| **${layer.name}** | ${layer.about} |`),
    ...t.middle,
  ];
  for (const [key, layer] of Object.entries(t.layers)) {
    const rules = ALL_RULES.filter((rule) => rule.layer === key);
    lines.push(t.section(layer.name, rules.length), '', t.columns, '|---|---|---|');
    for (const rule of rules) lines.push(`| \`${rule.id}\` | ${cell(rule.title)} | ${cell(publicSource(rule.source))} |`);
    lines.push('');
  }
  setLangSource(() => 'ko');
  return { target: t.target, text: lines.join('\n') };
}

const outputs = [build('en'), build('ko')];

if (process.argv.includes('--check')) {
  let failed = false;
  for (const { target, text } of outputs) {
    let current = '';
    try {
      current = readFileSync(target, 'utf8').replace(/\r\n/g, '\n');
    } catch {
      /* missing counts as a mismatch */
    }
    if (current !== text) {
      console.error(`[FAIL] ${target}가 코드와 다릅니다 — node scripts/make-rule-list.mjs 로 다시 만드십시오.`);
      failed = true;
    } else console.log(`✅ ${target} — 코드와 같습니다 (규칙 ${ALL_RULES.length}종)`);
  }
  if (failed) process.exit(1);
} else {
  for (const { target, text } of outputs) {
    writeFileSync(target, text);
    console.log(`${target}를 썼습니다 — 규칙 ${ALL_RULES.length}종`);
  }
}
